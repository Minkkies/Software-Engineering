export const iconNames = Object.keys(PATHS);

export default function Icon({
  name,
  size = 20,
  strokeWidth = 2,
  className = "",
  ...props
}) {
  const shape = PATHS[name];
  if (!shape) {
    if (process.env.NODE_ENV !== "production") {
      console.warn(`[Icon] ไม่พบไอคอนชื่อ "${name}"`);
    }
    return null;
  }

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={`shrink-0 ${className}`}
      {...props}
    >
      {shape}
    </svg>
  );
}